import type { Question } from "../types/question";

type Base = { id: string; lessonId: string; prompt: string; explanation?: string };
const short = (base: Base, acceptedAnswers: string[]): Question => ({ ...base, type: "shortAnswer", acceptedAnswers, explanation: base.explanation ?? `정답은 ${acceptedAnswers[0]}입니다.` });
const tf = (base: Base, correctAnswer: boolean): Question => ({ ...base, type: "trueFalse", correctAnswer, explanation: base.explanation ?? `정답은 ${correctAnswer ? "O" : "X"}입니다.` });
const choice = (base: Base, options: string[], correctAnswer: string): Question => ({ ...base, type: "multipleChoice", options, correctAnswer, explanation: base.explanation ?? `정답은 ${correctAnswer}입니다.` });
const multi = (base: Base, options: string[], correctAnswers: string[]): Question => ({ ...base, type: "multipleSelect", options, correctAnswers, explanation: base.explanation ?? `정답은 ${correctAnswers.join(", ")}입니다.` });
const b = (lessonId: string, id: number, prompt: string, explanation?: string): Base => ({ id: `${lessonId}-${String(id).padStart(2, "0")}`, lessonId, prompt, explanation });

