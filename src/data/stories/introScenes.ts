function dialogue(
  id: string,
  actorId: string,
  speakerName: string,
  text: string,
): StoryStep {
  return {
    id,
    type: "dialogue",
    speakerId: actorId,
    speakerName,
    activeActorId: actorId,
    text,
    advanceMode: "click",
  };
}

function narration(id: string, text: string): StoryStep {
  return { id, type: "narration", text, advanceMode: "click" };
}

function storySequence(
  id: string,
  title: string,
  backgroundId: string,
  backgroundUrl: string,
  steps: StoryStep[],
): StorySequence {
  return {
    id,
    title,
    scenes: [{ id: `${id}-scene`, steps }],
    backgrounds: {
      [backgroundId]: {
        imageUrl: backgroundUrl,
        placeholder: {
          label: title,
          gradient: "linear-gradient(180deg, #399eea, #162334)",
        },
      },
    },
    actors: {},
    replayable: true,
    skippable: true,
    onCompleteScreen: "story",
  };
}

